/**
 * One-shot Avalanche Fuji setup.
 *
 *   npm run fuji:setup
 *
 * Generates fresh facilitator / agent / platform wallets (or reuses an existing
 * .env.fuji), writes `.env.fuji` (gitignored — never committed), then checks
 * the Fuji RPC and prints the facilitator's AVAX balance + next steps.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createPublicClient, defineChain, http, formatEther } from 'viem';
import { generatePrivateKey, privateKeyToAccount } from 'viem/accounts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const envPath = path.join(root, '.env.fuji');

const RPC = 'https://api.avax-test.network/ext/bc/C/rpc';
const CHAIN_ID = 43113;
const FAUCET = 'https://faucet.avax.network';

const fuji = defineChain({
  id: CHAIN_ID,
  name: 'avalanche-fuji',
  nativeCurrency: { name: 'Avalanche', symbol: 'AVAX', decimals: 18 },
  rpcUrls: { default: { http: [RPC] } },
});
const pub = createPublicClient({ chain: fuji, transport: http(RPC) });

const log = (...a: unknown[]) => console.log(...a); // eslint-disable-line no-console

function readEnv(): Record<string, string> | null {
  if (!fs.existsSync(envPath)) return null;
  const out: Record<string, string> = {};
  for (const line of fs.readFileSync(envPath, 'utf8').split('\n')) {
    const m = line.match(/^([A-Z_]+)=(.*)$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

function isKey(v?: string): v is `0x${string}` {
  return !!v && /^0x[0-9a-fA-F]{64}$/.test(v);
}

function writeEnv(facilitatorKey: string, agentKey: string, platformAddr: string, platformKey: string) {
  const content = `# GateKeep — Avalanche Fuji testnet. Generated by \`npm run fuji:setup\`.
# REAL private keys — gitignored, never commit. Testnet only.

X402_MODE=chain
X402_NETWORK=avalanche-fuji
CHAIN_ID=43113
RPC_URL=${RPC}

# Filled in automatically by \`npm run fuji:deploy\`.
USDC_ADDRESS=
USDC_NAME=USD Coin
USDC_VERSION=2
USDC_DECIMALS=6

# Facilitator — FUND THIS with Fuji AVAX: ${FAUCET}
FACILITATOR_PRIVATE_KEY=${facilitatorKey}

# Demo agent — gets MockUSDC from the deploy step (no AVAX needed).
AGENT_PRIVATE_KEY=${agentKey}

# Platform treasury: receives gross USDC, pays out each seller's share on withdrawal.
# Fund it with a little AVAX so it can pay payout gas.
PLATFORM_WALLET=${platformAddr}
PLATFORM_PRIVATE_KEY=${platformKey}
PLATFORM_FEE_BPS=1000

# Session-signing secret — required in chain mode (the server refuses to boot
# with the public default). Generated fresh here.
JWT_SECRET=${crypto.randomBytes(32).toString('hex')}

PORT=4021
PUBLIC_BASE_URL=http://localhost:4021
`;
  fs.writeFileSync(envPath, content);
}

async function main() {
  const existing = readEnv();
  let facilitatorKey: string;
  let agentKey: string;
  let platformAddr: string;

  if (existing && isKey(existing.FACILITATOR_PRIVATE_KEY) && isKey(existing.AGENT_PRIVATE_KEY)) {
    facilitatorKey = existing.FACILITATOR_PRIVATE_KEY;
    agentKey = existing.AGENT_PRIVATE_KEY;
    platformAddr = existing.PLATFORM_WALLET ?? privateKeyToAccount(generatePrivateKey()).address;
    log('\n  Reusing wallets in existing .env.fuji.');
  } else {
    facilitatorKey = generatePrivateKey();
    agentKey = generatePrivateKey();
    const platformKey = generatePrivateKey();
    platformAddr = privateKeyToAccount(platformKey).address;
    writeEnv(facilitatorKey, agentKey, platformAddr, platformKey);
    log('\n  Generated fresh wallets → .env.fuji  (gitignored, never committed).');
  }

  const facilitator = privateKeyToAccount(facilitatorKey as `0x${string}`).address;
  const agent = privateKeyToAccount(agentKey as `0x${string}`).address;

  log('  ─────────────────────────────────────────────────────────────');
  log(`  facilitator  ${facilitator}   (pays gas — FUND THIS)`);
  log(`  agent        ${agent}   (holds USDC)`);
  log(`  platform     ${platformAddr}   (receives USDC)`);
  log('  ─────────────────────────────────────────────────────────────');

  try {
    const [chainId, bal] = await Promise.all([pub.getChainId(), pub.getBalance({ address: facilitator })]);
    log(`  Fuji RPC ok · chainId ${chainId} · facilitator balance ${formatEther(bal)} AVAX`);
    if (bal === 0n) {
      log('\n  ▶ NEXT:');
      log(`    1. Fund the facilitator with Fuji AVAX:  ${FAUCET}`);
      log(`       (paste ${facilitator})`);
      log('    2. npm run fuji:deploy     # deploy MockUSDC + mint to the agent');
      log('    3. npm run fuji:start      # run GateKeep against Fuji');
    } else {
      log('\n  ✓ facilitator funded — run `npm run fuji:deploy`, then `npm run fuji:start`.');
    }
  } catch (err) {
    log(`  ⚠️  could not reach Fuji RPC: ${err instanceof Error ? err.message : err}`);
  }
  log('');
}

main().catch((err) => {
  console.error('fuji:setup failed:', err instanceof Error ? err.message : err);
  process.exit(1);
});
